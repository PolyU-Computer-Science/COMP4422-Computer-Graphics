# Generates assets/knot.obj: a (2,3) torus-knot tube with v / vt / vn and quad faces.
# Run from the repo root:  python tools/gen_knot.py
import math
p, q, seg, sides, r = 2, 3, 160, 14, 0.28
def curve(t):
    rr = 2 + math.cos(q * t); return (rr * math.cos(p * t), rr * math.sin(p * t), -math.sin(q * t))
def sub(a, b): return [a[i] - b[i] for i in range(3)]
def cross(a, b): return [a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0]]
def norm(a):
    l = math.sqrt(sum(x * x for x in a)) or 1; return [x / l for x in a]
V, N, UV = [], [], []
for i in range(seg + 1):                      # seg+1 rings so the UV seam gets its own vertices
    t = 2 * math.pi * (i % seg) / seg; e = 1e-3
    c = curve(t); T = norm(sub(curve(t + e), curve(t - e)))
    B = norm(cross(T, list(c))); Nn = norm(cross(B, T))
    for j in range(sides + 1):
        a = 2 * math.pi * (j % sides) / sides
        n = [math.cos(a) * Nn[k] + math.sin(a) * B[k] for k in range(3)]
        V.append([c[k] + r * n[k] for k in range(3)]); N.append(n)
        UV.append([i / seg * 8, j / sides])   # u repeats 8x along the knot, v once around the tube
with open('assets/knot.obj', 'w') as f:
    f.write('# torus (2,3) knot tube, generated by tools/gen_knot.py for COMP4422 M1\n')
    for v in V: f.write('v %.5f %.5f %.5f\n' % tuple(v))
    for u in UV: f.write('vt %.5f %.5f\n' % tuple(u))
    for n in N: f.write('vn %.5f %.5f %.5f\n' % tuple(n))
    W = sides + 1
    for i in range(seg):
        for j in range(sides):
            a, b, c, d = i*W+j, i*W+j+1, (i+1)*W+j+1, (i+1)*W+j
            # counter-clockwise seen from outside (checked in test-math.js)
            f.write('f ' + ' '.join('%d/%d/%d' % (k+1, k+1, k+1) for k in (b, c, d, a)) + '\n')
print(len(V), 'verts')
